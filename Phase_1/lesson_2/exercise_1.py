# Exercise 1: Arithmetic
"""
Create:
a = 20
b = 6
Print the result of:
+
-
*
/
/
//
%
**
Also print the type of / and //.
"""

a=20
b=6

print(a+b, type(a+b))
print(a-b, type(a-b))
print(a*b, type(a*b))
print(a/b, type(a/b))
print(a//b, type(a//b)) # floor division
print(a%b, type(a%b)) # modulus
print(a**b, type(a**b)) # power/exponent
